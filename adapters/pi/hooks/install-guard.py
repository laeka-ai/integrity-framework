def _split_opts(words: list, tool: str, overrides: list) -> tuple:
    """(positionals, {option: [values]}) of *words*, honouring --opt=value and the tool's value-taking options."""
    takes = VALUE_OPTS.get(tool, set())
    pos, opts, i = [], {}, 0
    while i < len(words):
        w = words[i]
        if w == "--":
            pos.extend(words[i + 1:])
            break
        if w.startswith("-") and len(w) > 1:
            name, eq, val = w.partition("=")
            if name.startswith("--@") and name.endswith(":registry"):
                name = "--registry"                        # npm's --@scope:registry=URL
            if not eq and name in takes and i + 1 < len(words):
                val, i = words[i + 1], i + 1
            opts.setdefault(name, []).append(val)
            if name in OVERRIDE_OPTS.get(tool, ()):
                overrides.append("the option %s moves the registry, the index or the release-age setting" % name)
        else:
            pos.append(w)
        i += 1
    return pos, opts


def _npx_like(pos: list, opts: dict, eco: str) -> list:
    """npx, npm exec, pnpm dlx, yarn dlx, uvx: the --package values if any, else the first positional (the rest are
    the arguments of the program)."""
    named = opts.get("--package", []) + opts.get("-p", []) + opts.get("--from", []) + opts.get("--with", [])
    if named:
        return [(eco, v) for v in named if v]
    return [(eco, pos[0])] if pos else []


def install_requests(words: list, overrides: list, depth: int) -> list:
    """The (ecosystem, spec) pairs one simple command installs. Recurses into bash -c and eval."""
    words, via_xargs = _strip_prefix(words, overrides)
    if not words:
        return []
    verb = os.path.basename(words[0])
    rest = words[1:]
    if verb in ("export", "declare", "typeset", "local", "readonly"):
        for w in rest:
            _note_variable(w, overrides)
        return []
    if verb in SHELLS:
        for k, w in enumerate(rest):
            if w == "-c" or (w.startswith("-") and not w.startswith("--") and w.endswith("c")):
                return analyse(rest[k + 1], overrides, depth + 1) if k + 1 < len(rest) else []
        return []
    if verb == "eval":
        return analyse(" ".join(rest), overrides, depth + 1)
    if any(c in verb for c in "$`"):
        return []              # a computed verb: bash-boundary.py refuses it (computed_verb)
    if re.fullmatch(r"python\d*(\.\d+)?|py", verb):        # python -m pip install ... / python -mpip ...
        for k, w in enumerate(rest):
            if w.startswith("-m"):
                mod, skip = (rest[k + 1], 2) if w == "-m" and k + 1 < len(rest) else (w[2:], 1)
                if mod in ("pip", "uv"):
                    verb, rest = mod, rest[k + skip:]
                break
            if not w.startswith("-"):
                break
    if re.fullmatch(r"pip\d*(\.\d+)?", verb):
        verb = "pip"
    tool = {"pnpx": "pnpm", "npx": "npm", "uvx": "uv"}.get(verb, verb)
    if tool not in ("npm", "pnpm", "yarn", "pip", "uv", "poetry", "cargo", "pipx"):
        return []
    pos, opts = _split_opts(rest, tool, overrides)
    if verb in ("npx", "pnpx"):
        return _npx_like(pos, opts, "npm")
    if verb == "uvx":
        return _npx_like(pos, opts, "pypi")
    sub, args = (pos[0], pos[1:]) if pos else ("", [])
    if tool == "yarn" and sub == "global" and args:
        sub, args = args[0], args[1:]
    if tool == "uv" and sub in ("pip", "tool") and args:
        sub, args = sub + " " + args[0], args[1:]
    eco = {"npm": "npm", "pnpm": "npm", "yarn": "npm", "pip": "pypi", "uv": "pypi", "poetry": "pypi",
           "cargo": "crates", "pipx": "pypi"}[tool]
    if sub in ("config", "set") and tool in ("npm", "pnpm", "yarn", "pip", "poetry") and any(
            CONFIG_KEYS.search(a) for a in args):
        overrides.append("the command changes the config of %s (registry, index or release age)" % tool)
        return []
    if tool == "poetry" and sub == "source":
        overrides.append("the command changes poetry's package sources")
        return []
    npm_install = {"install", "i", "in", "ins", "inst", "insta", "instal", "isnt", "isnta", "isntal", "isntall",
                   "add", "update", "up", "upgrade", "udpate"}
    files = []                                             # requirements files named as positionals (uv pip sync)
    if (tool == "npm" and sub in npm_install) or (tool in ("pnpm", "yarn") and sub in npm_install):
        found = [(eco, a) for a in args]
    elif tool in ("npm", "pnpm", "yarn") and sub in ("exec", "x", "dlx"):
        found = _npx_like(args, opts, eco)
    elif tool == "pip" and sub in ("install", "download", "wheel"):
        found = [(eco, a) for a in args]
    elif tool == "uv" and sub == "tool run":
        found = _npx_like(args, opts, eco)
    elif tool == "uv" and sub in ("add", "pip install", "tool install"):
        found = [(eco, a) for a in args] + [(eco, v) for v in opts.get("--with", [])]
    elif tool == "uv" and sub == "pip sync":
        found, files = [], args
    elif tool == "uv" and sub == "run" and opts.get("--with"):
        found = [(eco, v) for v in opts["--with"]]
    elif tool == "poetry" and sub == "add":
        found = [(eco, a) for a in args]
    elif tool == "cargo" and sub in ("add", "install"):
        vers = (opts.get("--version") or opts.get("--vers") or [""])[0]
        found = [(eco, a + ("@=" + vers if vers and "@" not in a else "")) for a in args]
    elif tool == "pipx" and sub in ("install", "run", "inject", "upgrade"):
        found = [(eco, v) for v in opts.get("--spec", [])] or [(eco, a) for a in (args[:1] if sub == "run" else args)]
    else:
        return []
    if via_xargs:
        overrides.append("xargs feeds names to %s: they cannot be checked before it runs" % tool)
    for flag in ("-r", "--requirement", "--requirements", "-c", "--constraint", "--with-requirements"):
        files += opts.get(flag, [])
    for path in files:
        found.extend((eco, spec) for spec in _requirements_file(path, overrides))
    for path in opts.get("-e", []) + opts.get("--editable", []):
        found.append((eco, path))
    return found


def _requirements_file(path: str, overrides: list, depth: int = 0) -> list:
    """The specs a requirements file names; an option line that moves the index counts as an override."""
    if any(c in path for c in "$`") or depth > 3:
        raise Held("the requirements file %r cannot be read before it is used" % path)
    try:
        with open(os.path.join(BASE_DIR, path), encoding="utf-8") as f:
            lines = f.read().replace("\\\n", " ").splitlines()
    except OSError as exc:
        raise Held("the requirements file %r cannot be read (%s)" % (path, exc.__class__.__name__))
    specs = []
    for raw in lines:
        line = re.sub(r"(^|\s)#.*$", "", raw).strip()
        if not line:
            continue
        if line.startswith("-"):
            opt, _, val = re.sub(r"\s*=\s*|\s+", " ", line, count=1).partition(" ")
            val = val.strip()
            if opt in ("-r", "--requirement", "-c", "--constraint"):
                specs.extend(_requirements_file(os.path.join(os.path.dirname(path), val), overrides, depth + 1))
            elif opt in ("-e", "--editable"):
                specs.append(val)
            elif opt in REQUIREMENTS_OVERRIDES:
                overrides.append("the requirements file %r sets %s" % (path, opt))
            continue
        specs.append(line)
    return specs


def analyse(line: str, overrides: list, depth: int = 0) -> list:
    """Every (ecosystem, spec) the shell *line* installs, at any nesting up to MAX_DEPTH."""
    if depth > MAX_DEPTH:
        raise Held("the command nests shells deeper than the guard reads")
    line, apart = _bodies_apart(*_scan(line))
    try:
        segs = segments(line)
    except ValueError:
        raise Held("the command is unparseable (an unclosed quote this reader cannot split): it cannot be checked")
    found = []
    for seg in segs:
        found.extend(install_requests(seg, overrides, depth))
    for inner in substitutions(line) + apart:
        found.extend(analyse(inner, overrides, depth + 1))
    if OVERRIDE_WORDS.search(line):
        overrides.append("the command touches an installer's release-age setting")
    return found


# ── 2. One spec: name and requested version ────────────────────────────────────────────────────────────────────

LOCAL = re.compile(r"^(\.{1,2}(/.*)?|/.*|~/.*|file:.*)$")
REMOTE = re.compile(r"^(git\+|git:|github:|gitlab:|bitbucket:|gist:|https?:|ssh:|svn\+|hg\+|bzr\+)", re.IGNORECASE)
EXACT_SEMVER = re.compile(r"^=?v?\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?(\+[0-9A-Za-z.-]+)?$")


def parse_spec(eco: str, spec: str) -> dict:
    """{name, kind, version} with kind in exact | tag | latest | range | local | remote | computed."""
    if any(c in spec for c in "$`") or spec.startswith("-"):
        return {"name": spec, "kind": "computed", "version": ""}
    if LOCAL.match(spec) or (eco != "npm" and re.search(r"\.(whl|tar\.gz|zip|tgz)$", spec) and "/" in spec):
        return {"name": spec, "kind": "local", "version": ""}
    if REMOTE.match(spec) or " @ " in spec or re.match(r"^[\w.-]+\s*@\s*(https?|git\+|file):", spec):
        return {"name": spec, "kind": "remote", "version": ""}
    if eco == "npm":
        if re.search(r"\.(tgz|tar\.gz)$", spec):
            return {"name": spec, "kind": "local" if "/" in spec else "remote", "version": ""}
        scope = spec.startswith("@")
        name, at, ver = spec[1:].partition("@") if scope else spec.partition("@")
        name = ("@" + name) if scope else name
        if not scope and "/" in name:
            return {"name": spec, "kind": "remote", "version": ""}   # user/repo is a GitHub shorthand
        if ver.startswith("npm:"):                                     # an alias: alias@npm:real@version
            return parse_spec("npm", ver[4:])
        if not ver:
            return {"name": name, "kind": "latest", "version": "latest"}
        if EXACT_SEMVER.match(ver):
            return {"name": name, "kind": "exact", "version": ver.lstrip("=v")}
        if re.fullmatch(r"[A-Za-z][\w.-]*", ver) and not re.fullmatch(r"x|X|\*", ver):
            return {"name": name, "kind": "tag", "version": ver}
        return {"name": name, "kind": "range", "version": ver}
    if eco == "crates":
        name, _, ver = spec.partition("@")
        if not ver:
            return {"name": name, "kind": "latest", "version": ""}
        if re.fullmatch(r"=\s*\d+\.\d+\.\d+\S*", ver):
            return {"name": name, "kind": "exact", "version": ver.lstrip("= ")}
        return {"name": name, "kind": "range", "version": ver}
    # PyPI, PEP 508 (also poetry's name@version)
    spec = spec.split(";", 1)[0].strip()
    m = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)\s*(\[[^\]]*\])?\s*(.*)$", spec)
    if not m:
        return {"name": spec, "kind": "computed", "version": ""}
    name, ver = m.group(1), m.group(3).strip()
    if ver.startswith("@"):
        ver = ver[1:].strip()
        if ver == "latest":
            ver = ""
        elif re.fullmatch(r"\d[\w.!+-]*", ver):
            ver = "==" + ver
    if not ver:
        return {"name": name, "kind": "latest", "version": ""}
    exact = re.fullmatch(r"===?\s*([\w.!+-]+)", ver)
    if exact and "*" not in ver:
        return {"name": name, "kind": "exact", "version": exact.group(1)}
    return {"name": name, "kind": "range", "version": ver}


# ── 3. The registry ────────────────────────────────────────────────────────────────────────────────────────────

def _when(text) -> datetime | None:
    if not isinstance(text, str) or not text:
        return None
    t = text.strip().replace("Z", "+00:00")
    try:
        d = datetime.fromisoformat(t)
    except ValueError:
        try:
            d = datetime.fromisoformat(re.sub(r"\.\d+", "", t))
        except ValueError:
            return None
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def _get_json(url: str, timeout: float):
    """(status, document). 404 is (404, None); any other failure raises Held."""
    req = urllib.request.Request(url, headers={"Accept": "application/json",
                                               "User-Agent": "pi-install-guard/1"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            body = r.read(32 * 1024 * 1024)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return 404, None
        raise Held("the registry answered HTTP %d for %s" % (exc.code, url))
    except Exception as exc:  # noqa: BLE001: unreachable, timeout, TLS, reset: all are "cannot judge"
        raise Held("the registry is unreachable (%s)" % exc.__class__.__name__)
    try:
        return 200, json.loads(body)
    except ValueError:
        raise Held("the registry answered something that is not JSON for %s" % url)


def lookup(eco: str, name: str, cfg: dict) -> dict | None:
    """None when the registry does not know *name*; else {created, versions: {v: datetime|None}, latest, tags}."""
    base = cfg["registries"][eco].rstrip("/")
    if eco == "npm":
        status, doc = _get_json(base + "/" + urllib.parse.quote(name, safe="@"), cfg["timeout_s"])
        if status == 404 or not isinstance(doc, dict) or not doc.get("versions"):
            return None                                    # absent, or every version unpublished
        times = doc.get("time") or {}
        tags = doc.get("dist-tags") or {}
        return {"created": _when(times.get("created")), "tags": tags, "latest": tags.get("latest", ""),
                "versions": {v: _when(times.get(v)) for v in doc["versions"]}}
    if eco == "pypi":
        status, doc = _get_json(base + "/pypi/" + urllib.parse.quote(name) + "/json", cfg["timeout_s"])
        if status == 404 or not isinstance(doc, dict) or not doc.get("releases"):
            return None
        versions = {}
        for v, files in doc["releases"].items():
            dates = [_when(f.get("upload_time_iso_8601") or f.get("upload_time")) for f in files or []]
            dates = [d for d in dates if d]
            versions[v] = min(dates) if dates else None
        known = [d for d in versions.values() if d]
        return {"created": min(known) if known else None, "tags": {}, "versions": versions,
                "latest": (doc.get("info") or {}).get("version", "")}
    status, doc = _get_json(base + "/api/v1/crates/" + urllib.parse.quote(name), cfg["timeout_s"])
    if status == 404 or not isinstance(doc, dict) or not isinstance(doc.get("crate"), dict):
        return None
    crate = doc["crate"]
    versions = {v.get("num"): _when(v.get("created_at")) for v in doc.get("versions") or [] if isinstance(v, dict)}
    return {"created": _when(crate.get("created_at")), "tags": {}, "versions": versions,
            "latest": crate.get("max_stable_version") or crate.get("newest_version") or ""}


# ── 4. Look-alikes ─────────────────────────────────────────────────────────────────────────────────────────────

AFFIXES = {"js", "node", "py", "python", "lib", "cli", "dev", "api", "sdk", "core", "utils", "util", "official",
           "pkg", "plus", "pro", "2", "3", "x", "next", "new", "fix", "fixed", "secure", "tools"}
GLYPHS = str.maketrans({"0": "o", "1": "l", "i": "l", "5": "s", "3": "e", "4": "a", "7": "t"})


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name.lower())


def _osa(a: str, b: str, limit: int) -> int:
    """Optimal string alignment distance (Levenshtein plus adjacent transposition), cut at limit + 1."""
    if abs(len(a) - len(b)) > limit:
        return limit + 1
    prev2, prev = None, list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                cur[j] = min(cur[j], prev2[j - 2] + 1)
        prev2, prev = prev, cur
    return prev[-1]


def looks_like(name: str, popular: set) -> tuple | None:
    """(popular name, rule) when *name* (not itself popular) resembles one of *popular*, else None. The popular
    names are tried in a fixed order, unscoped first, then alphabetical: a set's own order changes with the hash
    seed of each process, and the receipt would name express in one run and @types/express in the next."""
    full = _norm(name)
    if full in popular:
        return None
    bare = full.split("/", 1)[1] if full.startswith("@") and "/" in full else full
    flat = bare.replace("-", "")
    for p in sorted(popular, key=lambda q: (q.startswith("@"), q)):
        pb = p.split("/", 1)[1] if p.startswith("@") and "/" in p else p
        pflat = pb.replace("-", "")
        if bare == pb:
            return p, "the same name under another scope"
        if flat == pflat:
            return p, "the same letters with other separators"
        if flat.translate(GLYPHS) == pflat.translate(GLYPHS):
            return p, "look-alike characters"
        for affix in AFFIXES:
            if flat in (pflat + affix, affix + pflat):
                return p, "the popular name with %r added" % affix
        if len(pflat) >= 4:
            limit = 2 if len(pflat) >= 8 else 1
            if _osa(bare, pb, limit) <= limit:
                return p, "%d edit(s) away" % _osa(bare, pb, limit)
    return None


# ── 5. The base of malicious packages ─────────────────────────────────────────────────────────────────────────────────────────────

def _base_name(eco: str, name: str) -> str:
    """A name as its registry tells names apart: PyPI folds case and -_. (PEP 503), crates.io case and -_, npm case."""
    if eco == "pypi":
        return _norm(name)
    return name.lower().replace("_", "-") if eco == "crates" else name.lower()


def _release(version: str) -> str:
    # shortcut: folds case, a leading v and trailing zeros only (PEP 440 ==v1.0 is 1.0.0), other spellings go on to the
    # registry check, upgrade to a full PEP 440 comparison if a listed version is ever reached that way.
    return re.sub(r"(\.0+)+$", "", version.lower().removeprefix("v"))


def load_malicious(cfg: dict) -> dict:
    """{ecosystem: {name: [(versions or "all", MAL id), ...]}}. It raises on anything it cannot trust, an empty
    base included: an emptied file must not read as "nothing is malicious"."""
    with open(cfg["malicious_file"], encoding="utf-8") as f:
        rows = json.load(f)["packages"]
    if not isinstance(rows, list) or not rows:
        raise ValueError("it lists no package")
    base = {}
    for eco, name, versions, mal in rows:
        if versions != "all" and not isinstance(versions, list):
            raise ValueError("a row has no versions")
        base.setdefault(eco, {}).setdefault(_base_name(eco, name), []).append((versions, mal))
    return base


def malicious(eco: str, spec: str, base: dict) -> str | None:
    """The receipt when the base rules this request out, else None. No registry call: this comes before all else."""
    p = parse_spec(eco, spec)
    if p["kind"] in ("local", "remote", "computed"):
        return None
    listed = base.get(eco, {}).get(_base_name(eco, p["name"]))
    if not listed:
        return None
    said = "%s package %r version %s: refused because OpenSSF lists " % (eco, p["name"], p["version"] or "latest")
    whole = [mal for versions, mal in listed if versions == "all"]
    if whole:
        return said + "every version as malicious (%s)" % ", ".join(whole)
    if p["kind"] == "exact":
        hits = [mal for versions, mal in listed if _release(p["version"]) in map(_release, versions)]
        return said + "this version as malicious (%s)" % ", ".join(hits) if hits else None
    bad = sorted({"%s: %s" % (mal, v) for versions, mal in listed for v in versions})
    return said + "versions of it as malicious (%s) and this request may resolve to one: pin a version that is not " \
                  "listed" % "; ".join(bad[:8])


# ── 6. The verdict ─────────────────────────────────────────────────────────────────────────────────────────────

def _days(since: datetime | None, now: datetime) -> float | None:
    return None if since is None else (now - since).total_seconds() / DAY


def _age(days: float | None) -> str:
    if days is None:
        return "unknown"
    return "%.1f days" % days if days < 2 else "%d days" % int(days)


def judge(eco: str, spec: str, cfg: dict, popular: dict, now: datetime) -> dict:
    """One package: {ecosystem, name, version, name_age_days, version_age_days, reasons}. Empty reasons = it may run."""
    p = parse_spec(eco, spec)
    out = {"ecosystem": eco, "name": p["name"], "version": p["version"] or "latest",
           "name_age_days": None, "version_age_days": None, "reasons": []}
    if p["kind"] == "local":
        return out                                         # the agent's own files: no registry fetch
    if p["kind"] == "computed":
        out["reasons"].append("the package name is computed or unreadable, it cannot be checked")
        return out
    if p["kind"] == "remote":
        out["reasons"].append("the package comes from a URL, git or another source than the registry")
        return out
    info = lookup(eco, p["name"], cfg)
    if info is None:
        out["reasons"].append("the registry does not know this name (an invented or removed package)")
        return out
    out["name_age_days"] = _days(info["created"], now)
    versions = info["versions"]
    if p["kind"] == "exact":
        target = p["version"] if p["version"] in versions else None
        if target is None:
            out["reasons"].append("version %s was never published" % p["version"])
    elif p["kind"] == "tag":
        target = info["tags"].get(p["version"])
        if target is None:
            out["reasons"].append("the tag %s does not exist" % p["version"])
    elif p["kind"] == "latest":
        target = info["latest"] or None
        if target is None:
            out["reasons"].append("the registry names no latest version")
    else:   # a range: the youngest published version bounds what it may resolve to
        dated = [(d, v) for v, d in versions.items() if d]
        target = max(dated)[1] if dated else None
        if target is None:
            out["reasons"].append("no version carries a publish date")
    if target is not None:
        out["version"] = target if p["kind"] != "range" else "%s (may resolve to %s)" % (p["version"], target)
        out["version_age_days"] = _days(versions.get(target), now)
        if out["version_age_days"] is None:
            out["reasons"].append("version %s has no publish date" % target)
        elif out["version_age_days"] < cfg["min_version_age_days"]:
            out["reasons"].append("version %s was published %s ago, under %d days"
                                  % (target, _age(out["version_age_days"]), cfg["min_version_age_days"]))
        if eco == "npm" and str(target).endswith("-security"):
            out["reasons"].append("npm replaced this package by a security placeholder")
    young = out["name_age_days"] is None or out["name_age_days"] < cfg["lookalike_max_age_days"]
    if young:
        hit = looks_like(p["name"], popular.get(eco, set()))
        if hit:
            out["reasons"].append("the name is %s old and looks like the popular %r (%s)"
                                  % (_age(out["name_age_days"]), hit[0], hit[1]))
    return out


def load_config() -> dict:
    cfg = json.loads(json.dumps(DEFAULTS))
    if os.path.exists(CONFIG_FILE):
        with open(CONFIG_FILE, encoding="utf-8") as f:
            given = json.load(f)
        if not isinstance(given, dict):
            raise ValueError("the config is not a JSON object")
        cfg["registries"].update(given.pop("registries", {}) or {})
        cfg.update(given)
    for eco in ("npm", "pypi", "crates"):
        if not isinstance(cfg["registries"].get(eco), str):
            raise ValueError("no registry URL for %s" % eco)
    with open(cfg["popular_file"], encoding="utf-8") as f:
        pop = json.load(f)
    cfg["popular"] = {eco: {_norm(n) for n in pop.get(eco, [])} for eco in ("npm", "pypi", "crates")}
    return cfg


def host_authorised(command: str) -> bool:
    """True when the HOST has authorised this exact command (same file and fields as the adapter's
    autorisation_hote: commande_sha256, expire_le). Fail-closed: any doubt is no."""
    sha = hashlib.sha256(command.strip().encode("utf-8")).hexdigest()
    try:
        with open(AUTHORISATIONS, encoding="utf-8", errors="replace") as f:
            for line in f:
                try:
                    e = json.loads(line)
                except ValueError:
                    continue
                if not isinstance(e, dict) or e.get("commande_sha256") != sha:
                    continue
                exp = e.get("expire_le")
                if exp and (_when(exp) is None or _when(exp) < datetime.now(timezone.utc)):
                    continue
                return True
    except OSError:
        return False
    return False


def _journal(entry: dict) -> None:
    try:
        os.makedirs(os.path.dirname(JOURNAL), exist_ok=True)
        with open(JOURNAL, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except OSError:
        pass


HOLD_HEAD = "BLOCKED [install-guard] Install held: this command installs something the guard cannot vouch for yet.\n"
HOLD_TAIL = ("   You cannot approve this yourself. Tell the person which package you want, why, and the receipt\n"
             "   lines above, then wait for their yes before you run it again.\n")
REFUSED_HEAD = "BLOCKED [install-guard] Install refused: the OpenSSF base of malicious packages rules this out.\n"
REFUSED_TAIL = ("   This is final: neither you nor the person can approve this command. Tell the person which package\n"
                "   it was and the receipt lines above.\n")
NO_BASE_TAIL = ("   Nothing is installed until the base is back, and a yes does not lift this. Tell the person, with the\n"
                "   receipt line above.\n")


def hold(command: str, lines: list, packages: list, head: str = HOLD_HEAD, tail: str = HOLD_TAIL,
         decision: str = "held") -> None:
    sys.stderr.write(head + "".join("   RECEIPT %s\n" % l for l in lines) + tail)
    _journal({"ts": datetime.now(timezone.utc).isoformat(), "decision": decision,
              "command_sha256": hashlib.sha256(command.strip().encode("utf-8")).hexdigest(),
              "command": command[:300], "receipts": lines, "packages": packages})
    sys.exit(2)


def receipt(p: dict) -> str:
    return ("%s package %r version %s: name first published %s ago, this version %s ago; held because %s"
            % (p["ecosystem"], p["name"], p["version"], _age(p["name_age_days"]), _age(p["version_age_days"]),
               "; ".join(p["reasons"])))


def command_of(raw: str) -> str:
    d = json.loads(raw or "")
    if not isinstance(d, dict) or "_pi_hooks_truncated" in d:
        raise Held("the hook context is unreadable or truncated")
    args = d.get("tool_args") or d.get("toolArgs")
    if not isinstance(args, dict) or "_pi_hooks_tool_args_truncated" in args:
        raise Held("the tool arguments are unreadable or truncated")
    cmd = args.get("command")
    if not isinstance(cmd, str):
        raise Held("no command in the tool arguments")
    global BASE_DIR
    cwd = d.get("cwd")
    BASE_DIR = cwd if isinstance(cwd, str) and os.path.isabs(cwd) else os.environ.get("PWD", "/srv/agent/workshop")
    return cmd


def main() -> int:
    command = ""
    try:
        command = command_of(sys.stdin.read())
        overrides = []
        requests = analyse(command, overrides)
        if not requests and not overrides:
            return 0
        cfg = load_config()
        if requests:
            try:
                base = load_malicious(cfg)
            except Exception as exc:  # noqa: BLE001: whatever broke the base, it was not read
                hold(command, ["command: the guard could not read its malicious-package base (%s: %s)"
                               % (exc.__class__.__name__, exc)], [], tail=NO_BASE_TAIL)
            refused = [r for r in dict.fromkeys(malicious(eco, spec, base) for eco, spec in requests) if r]
            if refused:
                hold(command, refused, [], REFUSED_HEAD, REFUSED_TAIL, "refused")
        if host_authorised(command):
            _journal({"ts": datetime.now(timezone.utc).isoformat(), "decision": "authorised-by-host",
                      "command_sha256": hashlib.sha256(command.strip().encode("utf-8")).hexdigest(),
                      "command": command[:300]})
            return 0
        now = datetime.now(timezone.utc)
        seen, verdicts = set(), []
        for eco, spec in requests:
            if (eco, spec) in seen:
                continue
            seen.add((eco, spec))
            try:
                verdicts.append(judge(eco, spec, cfg, cfg["popular"], now))
            except Held as exc:
                verdicts.append({"ecosystem": eco, "name": spec, "version": "?", "name_age_days": None,
                                 "version_age_days": None, "reasons": [str(exc)]})
        lines = ["command: " + r for r in dict.fromkeys(overrides)]
        lines += [receipt(v) for v in verdicts if v["reasons"]]
        if lines:
            hold(command, lines, verdicts)
        _journal({"ts": now.isoformat(), "decision": "passed",
                  "command_sha256": hashlib.sha256(command.strip().encode("utf-8")).hexdigest(),
                  "packages": verdicts})
        return 0
    except SystemExit:
        raise
    except Held as exc:
        hold(command, ["command: " + str(exc)], [])
    except Exception as exc:  # noqa: BLE001: a guard that breaks holds, it never lets the install through
        hold(command, ["command: the install guard failed (%s: %s)" % (exc.__class__.__name__, exc)], [])
    return 2


if __name__ == "__main__":
    sys.exit(main())
