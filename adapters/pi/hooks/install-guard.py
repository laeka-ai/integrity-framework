def _heredoc_word(line: str, i: int) -> tuple:
    """The here-document operator at line[i] (<< or <<-) and its word: (length of both, strip_tabs, quoted,
    delimiter). The delimiter is the word after quote removal; None when this reader cannot tell it (no word, an
    unclosed quote, a backslash between double quotes, $'...' or $"..." or a backtick in the word)."""
    j = i + 2
    strip = line.startswith("-", j)
    j += strip
    while j < len(line) and line[j] in " \t":
        j += 1
    k, parts, quoted = j, [], False
    while k < len(line) and line[k] not in WORD_BREAK:
        c = line[k]
        if c in "'\"":
            close = line.find(c, k + 1)
            if close < 0 or (c == '"' and "\\" in line[k + 1:close]):
                return k - i, strip, True, None
            parts.append(line[k + 1:close])
            quoted, k = True, close + 1
        elif c == "\\":
            parts.append(line[k + 1:k + 2])
            quoted, k = True, k + 2
        elif c == "`" or line.startswith(("$'", '$"'), k):
            return k - i, strip, quoted, None
        else:
            parts.append(c)
            k += 1
    return k - i, strip, quoted, ("".join(parts) if k > j else None)


def _heredoc_body(line: str, i: int, doc: dict) -> tuple:
    """(end of the body, end of its terminator line) for a body that starts at line[i]. No terminator: bash reads
    the body to the end of the text."""
    j = i
    while j < len(line):
        e = line.find("\n", j)
        e = len(line) if e < 0 else e
        text = line[j:e]
        if (text.lstrip("\t") if doc["strip"] else text) == doc["delim"]:
            return j, min(e + 1, len(line))
        j = e + 1
    return len(line), len(line)


def _scan(line: str) -> tuple:
    """(line without its shell comments, its here-documents). A comment runs from an unquoted # that starts a word
    to the end of its line, the line break kept (it still ends a command). Not a comment: a # inside '...', "...",
    $'...', backticks, ${...} or $((...)), or one inside a word (a#b, $#, ${#x}, $((16#ff)), a\\ #b, $(x)#y). Inside
    (...) or $(...) a comment runs to the end of the line, closing parenthesis included, as in bash (measured, bash
    5.2.21). A comment that names an installer or a release-age setting is kept (the safe side: a quoting form
    this reader does not model could make bash run it).

    A here-document body (the lines after the line of its << operator, up to its delimiter) is copied as it is:
    whether it is data or commands depends on who reads it, which analyse() decides. Each here-document is
    returned with its places in the returned text: "op" (the operator), "line" (start and end of the operator's
    line, its line break excluded), "start", "body_end" and "end" (the body, then past its terminator line), and
    "body", "quoted", "top" (outside any nesting). A word this reader cannot delimit keeps the rest of the text as it
    is, read as commands (the safe side)."""
    out, stack, i, n, word_start = [], [], 0, len(line), True
    pos, line_start, pending, docs = 0, 0, [], []
    while i < n:
        c, top = line[i], (stack[-1] if stack else "")
        code = all(s in CODE for s in stack)
        step, glued = 1, False                             # glued: the word goes on after this step
        if top == "'":
            if c == "'":
                stack.pop()
        elif c == "\\":
            step, glued = 2, True
        elif top in ("$'", "`"):
            if c == top[-1]:
                stack.pop()
        elif (top, c) in (('"', '"'), ("${", "}")):
            stack.pop()
        elif top == "$((" and line.startswith("))", i):
            step = 2
            stack.pop()
        elif line.startswith("$((", i):
            step = 3
            stack.append("$((")
        elif line.startswith(("$(", "${"), i):
            step = 2
            stack.append(line[i:i + 2])
        elif c == "`":
            stack.append(c)
        elif top == '"':
            pass                                           # any other character between double quotes is text
        elif line.startswith("$'", i):
            step = 2
            stack.append("$'")
        elif c in "'\"(":
            stack.append(c)
        elif c == ")" and top in CODE:
            stack.pop()
            glued = top == "$("                            # $(x)#y is one word
        elif code and line.startswith("<<<", i):
            step = 3                                       # a here-string is a word, not a here-document
        elif code and line.startswith("<<", i):
            step, strip, quoted, delim = _heredoc_word(line, i)
            if delim is None:
                out.append(line[i:])                       # cannot delimit: the rest stays, read as commands
                return "".join(out), docs
            pending.append({"op": pos, "strip": strip, "quoted": quoted, "delim": delim, "top": not stack})
        elif code and c == "#" and word_start:
            end = line.find("\n", i)
            end = n if end < 0 else end
            comment = line[i:end]
            if not (INSTALL_HINT.search(comment) or OVERRIDE_WORDS.search(comment)):
                i = end                                    # the comment goes, its line break stays
                continue
        elif code and c == "\n" and pending:              # the bodies follow this line break, in operator order
            out.append(c)
            pos, i = pos + 1, i + 1
            for doc in pending:
                body_end, after = _heredoc_body(line, i, doc)
                doc.update(line=(line_start, pos - 1), start=pos, body=line[i:body_end],
                           body_end=pos + body_end - i, end=pos + after - i)
                out.append(line[i:after])
                pos, i = pos + after - i, after
                docs.append(doc)
            pending, line_start, word_start = [], pos, True
            continue
        out.append(line[i:i + step])
        pos += len(out[-1])
        word_start = not glued and line[i + step - 1] in WORD_BREAK
        if code and c == "\n":
            line_start = pos
        i += step
    return "".join(out), docs


def _without_comments(line: str) -> str:
    """*line* without its shell comments (see _scan): what bash runs is unchanged."""
    return _scan(line)[0]


def _shell_reads(text: str, doc: dict) -> bool:
    """True when a shell may run this here-document's body as commands, the safe side when unsure: the operator
    sits in a nesting ($(...), backticks, a subshell: its output may become code), its line goes on after the body
    (it ends with |, |&, && or ||), its line cannot be split into words, a word of its line names a shell, source,
    eval or xargs (bash <<EOF, cat <<EOF | sh, while read l; do bash -c "$l"; done <<EOF), or a command of its line
    is `.`."""
    if not doc["top"]:
        return True
    op_line = text[doc["line"][0]:doc["line"][1]]
    try:
        tokens, segs = _tokens(op_line), segments(op_line)
    except ValueError:
        return True
    if tokens and tokens[-1] in ("|", "|&", "&&", "||"):
        return True
    for seg in segs:
        words, via_xargs = _strip_prefix(seg, [])
        if via_xargs or words[:1] == ["."] or any(os.path.basename(w) in SHELL_WORDS for w in seg):
            return True
    return False


def _bodies_apart(text: str, docs: list) -> tuple:
    """(text without its here-document bodies, the texts to read apart). A body a shell may run is read apart as
    commands; any other body is data, but bash still runs the $(...) and backticks of an unquoted one (cat <<EOF),
    so those are read apart; a quoted one (cat <<'EOF') is text only. The operator and its word stay: segments()
    drops them as a redirection."""
    apart = []
    for doc in reversed(docs):
        if _shell_reads(text, doc):
            apart.append(doc["body"])
        elif not doc["quoted"]:
            apart.extend(reversed(substitutions(doc["body"])))
        text = text[:doc["start"]] + text[doc["end"]:]
    return text, apart[::-1]


def _tokens(line: str) -> list:
    lex = shlex.shlex(line.replace("\\\n", " "), posix=True, punctuation_chars=PUNCT)
    lex.whitespace = " \t\r"
    lex.whitespace_split = True
    lex.commenters = ""
    return list(lex)


def segments(line: str) -> list:
    """The simple commands of *line*, as lists of words (quotes removed, redirections dropped). Comments are gone
    before: analyse() reads the line through _scan, so a # that reaches here is a word."""
    segs, cur, skip_next = [], [], False
    for tok in _tokens(line):
        if tok and all(c in PUNCT for c in tok):
            if "<" in tok or ">" in tok:                   # a redirection: drop its fd and its target
                if cur and (cur[-1].isdigit() or cur[-1] == "&"):
                    cur.pop()
                skip_next = not tok.endswith(("<(", ">("))
                if "\n" in tok or ";" in tok or "|" in tok:
                    segs.append(cur)
                    cur = []
                continue
            segs.append(cur)
            cur, skip_next = [], False
            continue
        if skip_next:
            skip_next = False
            continue
        cur.append(tok)
    segs.append(cur)
    return [s for s in segs if s]


def substitutions(line: str) -> list:
    """The texts inside $(...) and backticks, read even between double quotes (bash runs them there)."""
    found, i, n = [], 0, len(line)
    while i < n:
        if line.startswith("$(", i) and not line.startswith("$((", i):
            depth, j = 1, i + 2
            while j < n and depth:
                depth += {"(": 1, ")": -1}.get(line[j], 0)
                j += 1
            found.append(line[i + 2:j - 1] if depth == 0 else line[i + 2:])
            i = j
        elif line[i] == "`":
            j = line.find("`", i + 1)
            found.append(line[i + 1:] if j < 0 else line[i + 1:j])
            i = n if j < 0 else j + 1
        else:
            i += 1
    return found


def _note_variable(word: str, overrides: list) -> None:
    if ASSIGNMENT.match(word) and OVERRIDE_VARS.match(word):
        overrides.append("the variable %s changes an installer's registry or settings" % word.split("=")[0])


def _strip_prefix(words: list, overrides: list) -> tuple:
    """(the words from the real verb on, True if xargs feeds it), past the NAME=value words, keywords and launchers
    (with their options)."""
    i, via_xargs = 0, False
    while i < len(words):
        w = words[i]
        if ASSIGNMENT.match(w):
            _note_variable(w, overrides)
            i += 1
            continue
        if os.path.basename(w) in LAUNCHERS:
            via_xargs = via_xargs or os.path.basename(w) == "xargs"
            i += 1
            while i < len(words) and re.match(r"^(-\S*|\d\S*|[A-Za-z_][A-Za-z0-9_]*=\S*)$", words[i]):
                _note_variable(words[i], overrides)
                i += 1
            continue
        break
    return words[i:], via_xargs


