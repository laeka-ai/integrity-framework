#!/usr/bin/env python3
"""install-guard.py: the install guard of an unattended Pi agent.

A model sometimes invents a package name, an attacker publishes a trapped package under that name, and the agent
installs it (Spracklen et al., USENIX Security 2025: at least 5.2 % of the packages proposed by commercial models do
not exist, 21.7 % for open models, and 43 % of those names come back on every retry). This tool.before.bash hook
reads the shell line the agent is about to run, finds every install command in it (chained with && ; || | &, in a
subshell, in $(...) or backticks, in bash -c or eval, behind NAME=value prefixes, launchers or an absolute path),
extracts each package name and version, and first reads the OpenSSF base of malicious packages
(malicious-packages.json, regenerated by regenerate-malicious-packages.py from ossf/malicious-packages). A package
of that base is REFUSED before any other check and without the person's yes, and its receipt names the MAL-* id; a
pinned version the base does not list goes on, a request for no exact version of a package with listed versions is
refused too, since the guard cannot tell what it would resolve to. A base that cannot be read holds every install,
with no yes either: a yes cannot vouch for what could not be checked. Then it asks the configured registry about
each package. A package is HELD when:

  - the registry does not know the name (the invented library itself);
  - the pinned version, or the dist-tag, does not exist;
  - the version that would be installed was published less than min_version_age_days (7) ago;
  - the name was first published less than lookalike_max_age_days (180) ago and looks like a popular package;
  - it cannot be judged: a computed name ($X), a URL, git or remote source, an override of the registry or of the
    release-age setting, a requirements file that cannot be read, a registry that does not answer or answers garbage.

HELD is the same "ask before" path as bash-boundary.py: exit 2, a message
that tells the agent to ask the person and wait (it never shows a way around), and the person's yes arrives as a
line the HOST writes in the read-only authorisations file (PI_HOST_AUTHORIZATIONS), bound to the sha256 of the exact
command and carrying an expiry. Here the sha256 is taken over the command as the agent wrote it (stripped): it is the
text the receipt shows. Every hold prints one receipt line per package (ecosystem, name, version, ages, reason) and
journals it.

Contract, as write-guard.py: the pi-yaml-hooks context as JSON on stdin, the command in tool_args.command;
exit 0 = let it run, exit 2 = block. Any failure of this guard is exit 2: never a silent pass on error. A line with
no install command in it costs no network call.

The look-alike policy (a young name that resembles one of the popular packages is held, 180 days) follows ExactGround
(MIT, https://github.com/alidaram99/exactground). Its code was not read nor copied: the rules in `looks_like` are ours.

Config: a JSON file named by INSTALL_GUARD_CONFIG (default install-guard.json beside this file); absent, the
defaults below apply. Keys: registries {npm, pypi, crates}, min_version_age_days, lookalike_max_age_days,
popular_file, malicious_file, timeout_s. A config that exists but cannot be read holds every install.
"""
